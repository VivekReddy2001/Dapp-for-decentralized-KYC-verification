#!/usr/bin/env node
'use strict';

/**
 * Copies the freshly deployed contract's ABI, bytecode and address out of
 * Truffle's build artefact and into the file the browser reads.
 *
 * Every `truffle migrate` deploys a new contract at a new address. Before this
 * script existed, that address had to be pasted into src/js/contractDetails.js
 * by hand, and forgetting to do it is the single most common reason the pages
 * load but every call comes back empty.
 *
 * Usage:  npm run sync   (or: node scripts/sync-contract.js)
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const ARTEFACT = path.join(ROOT, 'build', 'contracts', 'kyc.json');
const TARGET = path.join(ROOT, 'src', 'js', 'contractDetails.js');

/** Everything from this marker down is hand-maintained UI config — never overwritten. */
const KEEP_MARKER = '//  IDs of all elements of the KYC form';

function fail(message, hint) {
  console.error(`\n  ✖ ${message}`);
  if (hint) console.error(`    ${hint}`);
  console.error('');
  process.exit(1);
}

if (!fs.existsSync(ARTEFACT)) {
  fail(
    'No build artefact at build/contracts/kyc.json.',
    'Run `npm run compile` (and `npm run migrate`) first.'
  );
}

const artefact = JSON.parse(fs.readFileSync(ARTEFACT, 'utf8'));
const deployments = Object.entries(artefact.networks || {});

if (deployments.length === 0) {
  fail(
    'The contract has been compiled but never deployed.',
    'Start a chain with `npm run chain`, then run `npm run migrate`.'
  );
}

// Truffle keys deployments by network id. Take the most recent one.
const [networkId, deployment] = deployments[deployments.length - 1];
const { address } = deployment;

const previous = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
const keepFrom = previous.indexOf(KEEP_MARKER);
const preserved = keepFrom === -1 ? '' : previous.slice(keepFrom);

const generated = `//  Generated by scripts/sync-contract.js — do not edit the three values below by hand.
//  Re-run \`npm run sync\` after every \`npm run migrate\`.
//
//  Contract : ${artefact.contractName}
//  Network  : ${networkId}
//  Compiler : ${artefact.compiler ? `${artefact.compiler.name} ${artefact.compiler.version}` : 'unknown'}

var contractAddress = ${JSON.stringify(address)};

var abi = ${JSON.stringify(artefact.abi)};

var binaryData = ${JSON.stringify(artefact.bytecode)};

${preserved}`;

fs.writeFileSync(TARGET, generated);

console.log(`\n  ✔ src/js/contractDetails.js updated`);
console.log(`    contract : ${artefact.contractName} @ ${address}`);
console.log(`    network  : ${networkId}`);
console.log(`    abi      : ${artefact.abi.length} entries\n`);
